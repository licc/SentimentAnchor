import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:8787', { waitUntil: 'domcontentloaded' })
await page.waitForSelector('.anchor-card', { timeout: 20000 })
const initial = await page.evaluate(() => document.documentElement.dataset.theme)
await page.getByTitle('切换深色主题').click()
await page.waitForTimeout(500)
const dark = await page.evaluate(() => document.documentElement.dataset.theme)
await page.screenshot({ path: '/tmp/dark-top.png', fullPage: false })
await page.locator('#ai').scrollIntoViewIfNeeded()
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/dark-ai.png', fullPage: false })
await page.getByRole('button', { name: '全量监控' }).click()
await page.locator('#sentiment').scrollIntoViewIfNeeded()
await page.waitForTimeout(300)
await page.screenshot({ path: '/tmp/dark-sentiment.png', fullPage: false })
await page.locator('#calendar').scrollIntoViewIfNeeded()
await page.waitForTimeout(300)
await page.screenshot({ path: '/tmp/dark-calendar.png', fullPage: false })
await page.reload({ waitUntil: 'domcontentloaded' })
await page.waitForSelector('.anchor-card', { timeout: 20000 })
const afterReload = await page.evaluate(() => document.documentElement.dataset.theme)
console.log(JSON.stringify({ initial, dark, afterReload, errors }, null, 2))
await browser.close()
