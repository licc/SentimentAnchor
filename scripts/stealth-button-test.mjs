import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:8787', { waitUntil: 'domcontentloaded' })
await page.waitForSelector('.anchor-card', { timeout: 20000 })
await page.getByRole('button', { name: /阅读/ }).click()
await page.waitForSelector('.stealth-page', { timeout: 20000 })
const stealthUrl = page.url()
const stealthTitle = await page.title()
await page.screenshot({ path: '/tmp/agu-stealth-final.png', fullPage: false })
await page.locator('.stealth-back').click()
await page.waitForSelector('.hero', { timeout: 20000 })
const backUrl = page.url()
const backTitle = await page.title()
console.log(JSON.stringify({ stealthUrl, stealthTitle, backUrl, backTitle, errors }, null, 2))
await browser.close()
