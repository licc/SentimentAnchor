import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:8787/docs', { waitUntil: 'domcontentloaded' })
await page.waitForSelector('.stealth-page', { timeout: 20000 })
const title = await page.title()
const url = page.url()
const hasMarket = (await page.locator('body').innerText()).includes('涨停')
await page.screenshot({ path: '/tmp/agu-stealth.png', fullPage: false })
await page.keyboard.press('Alt+Shift+M')
await page.waitForSelector('.hero', { timeout: 20000 })
const backUrl = page.url()
const backTitle = await page.title()
await page.keyboard.press('Alt+Shift+M')
await page.waitForSelector('.stealth-page', { timeout: 20000 })
const reUrl = page.url()
console.log(JSON.stringify({ title, url, hasMarket, backUrl, backTitle, reUrl, errors }, null, 2))
await browser.close()
